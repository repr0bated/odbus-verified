#!/bin/bash
# Stage only a NEW successor of an imported seed; no existing guest/root edits.
# Usage: 16-stage-golden-runtime.sh BASE_NAME BASE_UUID NEW_NAME RECEIPT_DIR [RESUME_UUID]
set -euo pipefail
PATH=/usr/sbin:/usr/bin:/sbin:/bin
export PATH
[[ ( $# == 4 || $# == 5 ) && $(id -u) == 0 ]] || exit 2
base_name=$1 base_uuid=$2 new_name=$3 receipt_dir=$4 resume_uuid=${5:-}
[[ $base_name =~ ^@golden-[a-zA-Z0-9-]+$ && $new_name =~ ^@golden-[a-zA-Z0-9-]+$ && $base_name != "$new_name" && $receipt_dir == /var/lib/opdbus-release/* ]] || exit 2
. "$(dirname -- "$0")/lib.sh"
base=$POOL_DIR/images/$base_name
seed=$POOL_DIR/images/$new_name
uuid_of() { btrfs subvolume show "$1" | awk '$1=="UUID:" {print $2}'; }
readonly() { [[ $(btrfs property get -ts "$1" ro) == ro=true ]]; }
readonly "$base"; [[ $(uuid_of "$base") == "$base_uuid" ]] || exit 1
[[ -z $(btrfs subvolume list -o "$base") ]] || exit 1
[[ $(findmnt -rn -M "$POOL_DIR" -o UUID) == b6a13d79-ed2d-4057-8d0c-252fb7947f94 ]] || exit 1
install -d -m 0700 "$receipt_dir"
exec 9>"$receipt_dir/lock"; flock -n 9
phase=prepared
finish() {
  rc=$?
  jq -n --argjson exit "$rc" --arg phase "$phase" --arg at "$(date -u +%FT%TZ)" '{exit:$exit,phase:$phase,finished_at:$at}' >"$receipt_dir/completion.json.new"
  sync -f "$receipt_dir/completion.json.new"; mv -T "$receipt_dir/completion.json.new" "$receipt_dir/completion.json"; sync -f "$receipt_dir"
}
trap finish EXIT
if [[ -e $seed ]]; then
  [[ -n $resume_uuid && $(uuid_of "$seed") == "$resume_uuid" &&
    $(btrfs property get -ts "$seed" ro) == ro=false &&
    $(btrfs subvolume show "$seed" | awk '$1=="Parent" && $2=="UUID:" {print $3}') == "$base_uuid" ]] || fail 'unowned or sealed candidate'
else
  [[ -z $resume_uuid ]] || fail 'resume candidate is absent'
  btrfs subvolume snapshot "$base" "$seed"
fi
R=$seed/rootfs
artifacts=$R/opt/op-build/target/release
# Refuse credential-bearing image inputs. Public trust is a separate readonly
# declared disk; no host secret directory, database or daemon socket is copied.
[[ ! -e $R/agent/user/sealed_id ]] || fail 'image contains inherited identity credentials'
for directory in "$R/root/.ssh" "$R/etc/op-dbus/secrets"; do
  [[ ! -e $directory ]] || [[ -d $directory && ! -L $directory && -z $(find "$directory" -mindepth 1 -print -quit) ]] ||
    fail 'image contains inherited credentials'
done
# Remove only inherited credential copies in this NEW successor. The sealed
# base and every existing guest remain unchanged. New guest SSH keys are
# generated by its stage-1 owner; password login starts locked.
for key in "$R"/etc/ssh/ssh_host_*_key "$R"/etc/ssh/ssh_host_*_key.pub; do
  [[ ! -e $key ]] || rm -- "$key"
done
while IFS=: read -r user rest; do
  [[ $user =~ ^[a-zA-Z_][a-zA-Z0-9_-]*[$]?$ ]] || fail 'invalid local account name'
  chroot "$R" usermod --password '!' "$user"
done <"$R/etc/passwd"
[[ ! -e $R/etc/shadow- ]] || rm -- "$R/etc/shadow-"
[[ $(sha256sum "$artifacts/op-grpc-bridge" | cut -d' ' -f1) == 0baa6b9f4984ccd7acf1e40b474bb5191500b98573256b931efa3d33ef048cda ]] || fail 'Golden bridge artifact changed'
install -d -m 0755 "$R/usr/local/libexec/op-dbus/bin" "$R/usr/local/bin" "$R/etc/op-dbus" "$R/usr/share/op-dbus" "$R/etc/sv" "$R/etc/runit/runsvdir/default"
manifest='{}'
for binary in 3tched-fs op-grpc-bridge op-tunnel-door op-identity-accept; do
  [[ -x $artifacts/$binary ]] || fail "missing $binary"
  case $binary in op-identity-accept) destination=/usr/local/bin/$binary;; *) destination=/usr/local/libexec/op-dbus/bin/$binary;; esac
  install -m 0755 "$artifacts/$binary" "$R$destination"
  sha=$(sha256sum "$artifacts/$binary" | cut -d' ' -f1)
  [[ $(sha256sum "$R$destination" | cut -d' ' -f1) == "$sha" ]] || exit 1
  manifest=$(jq -c --arg binary "$binary" --arg path "$destination" --arg sha "$sha" '. + {($binary):{path:$path,sha256:$sha}}' <<<"$manifest")
done
install -m 0755 "$REPO/deploy/seed/rootfs/usr/local/libexec/op-dbus/door-tls-init" "$R/usr/local/libexec/op-dbus/door-tls-init"
write_guest_bridge_settings "$R"
# The retained sysv/native-boot stage-1 owner runs one short layout adapter.
install -d -m 0755 "$R/etc/runit/core-services" "$R/etc/init.d" "$R/etc/rcS.d" "$R/etc/runit/boot-run"
install -m 0644 "$HERE/runit/core-services/90-opdbus.sh" "$R/etc/runit/core-services/90-opdbus.sh"
install -m 0755 "$HERE/runit/core-services/opdbus-guest-layout" "$R/etc/init.d/opdbus-guest-layout"
ln -s /etc/init.d/opdbus-guest-layout "$R/etc/rcS.d/S99opdbus-guest-layout"
printf '/etc/init.d/opdbus-guest-layout start\n' >"$R/etc/runit/boot-run/S99-opdbus-guest-layout.stage1.sh"
for service in opdbus-lo door-tls-init 3tchedfs threetchedfs op-grpc-bridge op-tunnel-door nextdns; do
  [[ ! -e $R/etc/sv/$service && ! -L $R/etc/runit/runsvdir/default/$service ]] || fail "preexisting service $service"
  cp -a "$HERE/runit/$service" "$R/etc/sv/$service"
  ln -s "/etc/sv/$service" "$R/etc/runit/runsvdir/default/$service"
done
# jq is required by the declared guest owners, not supplied by the host's ABI.
phase=packages
if ! chroot "$R" sh -c 'command -v jq >/dev/null'; then
  chroot "$R" env DEBIAN_FRONTEND=noninteractive sh -c 'apt-get update -q && apt-get install -y -q --no-install-recommends jq'
fi
cache=/var/cache/op-dbus/provisioning
install -d -m 0755 "$cache"
archive=$cache/nextdns_${NEXTDNS_VERSION}_linux_amd64.tar.gz
if [[ ! -f $archive ]]; then
  curl --connect-timeout 15 --max-time 120 -fsSL "https://github.com/nextdns/nextdns/releases/download/v$NEXTDNS_VERSION/nextdns_${NEXTDNS_VERSION}_linux_amd64.tar.gz" -o "$archive.new"
  printf '%s  %s\n' "$NEXTDNS_SHA256" "$archive.new" | sha256sum -c -
  mv -T "$archive.new" "$archive"
fi
printf '%s  %s\n' "$NEXTDNS_SHA256" "$archive" | sha256sum -c -
tar -xzf "$archive" -C "$receipt_dir" nextdns
install -m 0755 "$receipt_dir/nextdns" "$R/usr/bin/nextdns"
manifest=$(jq -c --arg sha "$(sha256sum "$R/usr/bin/nextdns" | cut -d' ' -f1)" '. + {nextdns:{path:"/usr/bin/nextdns",sha256:$sha}}' <<<"$manifest")
# Refuse an incompatible boot owner instead of staging dormant services.
grep -q '/etc/rcS.d/S' "$R/etc/runit/1" || fail 'unsupported stage-1 owner'
[[ $(readlink "$R/sbin/init") == *runit* && -d $R/root && -d $R/etc ]] || exit 1
[[ -z $(btrfs subvolume list -o "$seed") ]] || fail 'nested subvolume would be omitted by snapshots'
jq -n --arg base "$base" --arg uuid "$base_uuid" --argjson binaries "$manifest" \
  '{version:1,base_seed:$base,base_seed_uuid:$uuid,binaries:$binaries,services:["opdbus-lo","door-tls-init","3tchedfs","threetchedfs","op-grpc-bridge","op-tunnel-door","nextdns"],credentials:"own readonly identity sled only; no image credentials",settings:"/etc/op-dbus/env/<name>",runtime_staged:false,payload_prepared:true,guest_readiness_verified:false}' >"$R/usr/share/op-dbus/golden-runtime.json"
sync -f "$seed"
# Keep this private candidate writable until fresh same-source artifacts and
# catalog are assembled by 17-finalize-golden-runtime.sh.
phase=payload-prepared
jq -n --arg base_uuid "$base_uuid" --arg seed "$seed" --arg name "$new_name" --arg uuid "$(uuid_of "$seed")" \
  --arg id "$(btrfs inspect-internal rootid "$seed")" --arg manifest_sha "$(sha256sum "$R/usr/share/op-dbus/golden-runtime.json" | cut -d' ' -f1)" --argjson binaries "$manifest" \
  '{version:1,phase:"payload-prepared",seed:$seed,seed_id:$id,seed_uuid:$uuid,parent_uuid:$base_uuid,pool_fsid:"b6a13d79-ed2d-4057-8d0c-252fb7947f94",seed_location:{incus_dir:"/var/lib/incus",pool:"3tched-pool",seed_dir:"images",seed_name:$name},runtime_staged:false,payload_prepared:true,runtime_manifest_sha256:$manifest_sha,binaries:$binaries,guest_readiness_verified:false}' >"$receipt_dir/receipt.json"
sync -f "$receipt_dir/receipt.json"; sync -f "$receipt_dir"
cat "$receipt_dir/receipt.json"
