#!/bin/sh
# Rebuild CONTEXT.md: every project document in priority order, scope first.
set -eu
cd "$(dirname "$0")/.."
out=CONTEXT.md
{
  echo "# CONTEXT — Etched in Schema (generated by tools/build-context.sh; do not edit)"
  echo
  for f in local/IDENTIFIERS.md AGENTS.md START-HERE.md README.md docs/DEV-CYCLE.md ui/README.md docs/DROP-IN-SPEC.md docs/RUNTIME.md SPARK-BRIEF.md docs/3TCHED-RESOURCES.md \
           docs/SUBSIDIARY-SLED.md docs/APPROVALS-SPEC.md docs/PRIOR-ART.md docs/WINNING.md review/out/findings.md \
           schema/index-entry.schema.json schema/llc-declaration.schema.json; do
    [ -f "$f" ] || continue
    echo; echo "---"; echo; echo "## FILE: \`$f\`"; echo
    case "$f" in *.json) echo '```json'; cat "$f"; echo '```' ;; *) cat "$f" ;; esac
  done
} > "$out"
echo "wrote $out ($(wc -l < "$out") lines)"
