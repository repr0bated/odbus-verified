/// One container's identity sled. The container is the sled is the identity:
/// `session_id` == container name == derived session identity.
#[derive(Debug, Clone, Serialize, Deserialize, schemars::JsonSchema)]
#[schemars(extend("x-oscal-subid" = "sch.service.identity-sled.record.schema@v1"))]
pub struct ContainerIdentitySled {
    /// Container identity: session_id = container name, derived from the
    /// WireGuard pubkey. The host is "container zero" under its own id.
    #[schemars(extend("x-oscal-subid" = "src.service.identity-sled.session-id@v1"))]
    pub session_id: String,
    /// WireGuard public key (base64) — the cryptographic root of identity.
    #[schemars(extend("x-oscal-subid" = "src.network.identity-sled.wireguard-pubkey@v1"))]
    pub wireguard_pubkey: String,
    /// WireGuard interface the identity is anchored to.
    #[serde(default)]
    pub interface: String,
    /// Peer IP on the WG mesh, when known (identity anchor for sub-HTTP protocols).
    #[serde(default)]
    pub peer_ip: Option<String>,
    /// Monotonic mutation index (accountability loop position).
    #[serde(default)]
    pub mutation_index: u64,
    /// Hex blake3 session genesis — the immutable identity anchor, minted once
    /// at arrival (first authenticated mutation) and never recomputed.
    /// Replaces the v2 `hashed_footprint` field; the serde alias lets old v2
    /// records deserialize into this field during migration.
    #[serde(default, alias = "hashed_footprint")]
    pub genesis: Option<String>,
    /// Hex trace id propagated across the session.
    #[serde(default)]
    pub trace_id: String,
    /// Published sled record schema version captured at identity arrival.
    #[serde(default)]
    pub schema_version: u32,
    /// Semantic vector id for the session, when embedded.
    #[serde(default)]
    pub vector_id: String,
    /// MutationEngine-authored inline SID1 identity envelope. This metadata is
    /// sealed at session arrival and is never supplied or rebuilt by callers.
    #[serde(default)]
    #[schemars(
        extend("readOnly" = true),
        extend("x-oscal-subid" = "src.service.identity-sled.sealed-id@v1")
    )]
    pub sealed_id: Option<String>,
    /// Actor class for implicit session selection: `human` or `service`.
    /// This is not the SID1 envelope's `principal_kind` (always
    /// `wireguard-principal`). Do not seal this value into SID1.
    #[serde(default)]
    #[schemars(extend("x-oscal-subid" = "src.service.identity-sled.actor-class@v1"))]
    pub principal_kind: Option<String>,
    /// Private persistence leaf assigned to this identity in Cozo. The host
    /// provisioner creates its permanent relationship to the shared seed.
    /// Login/start/stop only verify that relationship and update logical
    /// attachment; they never add or remove Btrfs filesystem members.
    #[serde(default)]
    #[schemars(extend("x-oscal-subid" = "src.service.identity-sled.btrfs-device@v1"))]
    pub btrfs_device: Option<SledBtrfsDevice>,
    /// The container's full Incus definition (official `shared/api` shape) —
    /// the sled inherits the Incus schema; provisioning the container IS
    /// writing this sled. The instance name is the session ID except for the
    /// configured control-plane chatbot's narrowly validated native alias.
    #[serde(default)]
    #[schemars(extend("x-oscal-subid" = "src.service.identity-sled.instance@v1"))]
    pub instance: Option<super::incus::IncusInstance>,
    /// Unix seconds when the session began.
    #[serde(default)]
    pub session_started_at: i64,
    /// Unix seconds of the last heartbeat / arrival.
    #[serde(default)]
    pub last_seen_at: i64,
    /// Whether the identity has a live authenticated session term. For a
    /// provisioned container this is also its power policy: active means
    /// running; inactive means stopped and parked (never deleted).
    #[serde(default)]
    pub active: bool,
    /// Unix seconds the *current visit/term* stops being valid. The account
    /// (session_id) can be lifelong (host/user/chatbot) while still having a
    /// bounded term — lifelong accounts get this renewed on every touch
    /// (`touch_identity_sled`); temporary consumer identities (e.g. external
    /// frontends like Lovable) don't, so their term actually lapses.
    /// `None` before a term has ever been issued.
    #[serde(default)]
    #[schemars(extend("x-oscal-subid" = "src.service.identity-sled.expires-at@v1"))]
    pub expires_at: Option<i64>,
    /// Unix seconds of the arrival event (first authenticated mutation).
    /// Stored immutably for offline re-verification.
    #[serde(default)]
    pub arrival_timestamp: i64,
    /// Hex hash of the chain head at genesis mint time.
    #[serde(default)]
    pub chain_head_at_arrival: String,
    /// Hex hash of the schema catalog at genesis mint time.
    #[serde(default)]
    pub catalog_hash_at_arrival: String,
    /// Timestamp of the chain head event at genesis mint time.
    #[serde(default)]
    pub head_timestamp_at_arrival: i64,
}

impl ContainerIdentitySled {
    /// Whether this account's arrival has been anchored by `mint_genesis`.
    ///
    /// A non-empty `genesis` is not sufficient on its own. A version-2 record's
    /// `hashed_footprint` lands in `genesis` through the serde alias above, so
    /// it *looks* anchored while carrying a value that was never minted and has
    /// no inputs behind it — nothing could re-derive or re-verify it. An anchor
    /// counts only when the inputs it was minted from came with it.
    ///
    /// This is the one definition of "anchored". The accept path uses it to
    /// decide whether to mint, and the write path uses it to decide whether a
    /// record may be overwritten; if they disagreed, a v2 record would be
    /// rejected forever by one and refused a mint by the other.
    pub fn is_anchored(&self) -> bool {
        self.genesis.as_deref().is_some_and(|g| !g.is_empty())
            && self.arrival_timestamp != 0
            && !self.chain_head_at_arrival.is_empty()
    }
}

/// The identity's private writable Btrfs leaf. Cozo owns its assignment;
/// the external host provisioner owns its seed pairing and mounts. The leaf
/// may be a block device or a persistent loop-backed file.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq, schemars::JsonSchema)]
#[schemars(extend("x-oscal-subid" = "sch.service.identity-sled.btrfs-device.schema@v1"))]
pub struct SledBtrfsDevice {
    /// Writable leaf block device or backing file, never the shared seed.
    pub device_path: String,
    /// Externally prepared mount of the identity filesystem.
    #[serde(default)]
    pub mount_point: String,
    /// btrfs filesystem UUID of the leaf.
    #[serde(default)]
    pub btrfs_uuid: String,
    /// Cozo owner key for the selected device binding. Newly provisioned
    /// leaves use the derived identity_sessions session key, whose row owns
    /// btrfs_device_json; repaired legacy records retain their prior value.
    #[serde(default)]
    pub cozo_id: String,
    /// Logical identity attachment after verifying the prepared filesystem.
    /// False does not mean the leaf was removed from its Btrfs filesystem.
    #[serde(default)]
    pub attached: bool,
}

