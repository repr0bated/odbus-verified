    /// and asserts the hash differs.
    #[test]
    fn schema_content_hash_drift() {
        use sha2::{Digest, Sha256};

        let src = include_str!("identity_sled.rs");
        let struct_body = extract_struct_body_test(src, "ContainerIdentitySled")
            .expect("struct definition found");

        // Verify the build-script hash matches the current source.
        let current_hash = hex_encode(&Sha256::digest(struct_body.as_bytes()));
        assert_eq!(
            current_hash, SCHEMA_CONTENT_HASH,
            "SCHEMA_CONTENT_HASH must match the current struct definition"
        );

        // Insert a dummy field before the closing brace to simulate a change.
        let modified = format!(
            "{}    pub __drift_test_field: String,\n}}",
            &struct_body[..struct_body.len() - 1]
        );
        let modified_hash = hex_encode(&Sha256::digest(modified.as_bytes()));
        assert_ne!(
            modified_hash, SCHEMA_CONTENT_HASH,
            "hash must change when a field is added to the struct"
        );
    }

    /// Extract `pub struct <name> { ... }` text, matching build.rs logic.
    fn extract_struct_body_test(src: &str, struct_name: &str) -> Option<String> {
        let needle = format!("pub struct {struct_name} {{");
        let start = src.find(&needle)?;
        let brace_start = src[start..].find('{')? + start;
        let mut depth = 0i32;
        let mut end = brace_start;
        for (i, ch) in src[brace_start..].char_indices() {
            match ch {
                '{' => depth += 1,
                '}' => {
                    depth -= 1;
                    if depth == 0 {
                        end = brace_start + i + 1;
                        break;
                    }
                }
                _ => {}
            }
        }
        Some(src[start..end].to_string())
    }

    fn hex_encode(bytes: &[u8]) -> String {
        let mut out = String::with_capacity(bytes.len() * 2);
        for &b in bytes {
            out.push_str(&format!("{b:02x}"));
        }
        out
    }
