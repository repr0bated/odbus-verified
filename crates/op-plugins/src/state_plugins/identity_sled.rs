#[async_trait]
impl StatePlugin for IdentitySledPlugin {
    fn name(&self) -> &str {
        "identity_sled"
    }

    // v4.5 adopts an externally prepared fresh container with same-key CAS.
    // v4.4.1 corrects storage lifecycle documentation: attachment is logical;
    // start/stop never mutates Btrfs membership. Wire fields are unchanged.
    // Plugin contract v4.4 adds a separately granted, credential-free own read.
    // v4.3 added owner-only physical-root provenance migration.
    // The native Device discriminants remain unchanged.
    // SID1, RECORD_FORMAT and durable identity record/revision formats do not change.
    fn version(&self) -> &str {
        "4.7.0"
    }

    fn schema(&self) -> Option<PluginSchema> {
        let mut schema = super::plugin_scaffold_helpers::identity_sled_plugin_schema();
        super::common::oscal::ensure_category_metadata_fields(&mut schema);
        Some(schema)
    }

    async fn calculate_diff(&self, _current: &Value, _desired: &Value) -> Result<StateDiff> {
        anyhow::bail!(
            "identity changes require the canonical identity owner; generic reconciliation is unsupported"
        )
    }

    async fn apply_state(&self, _diff: &StateDiff) -> Result<ApplyResult> {
        anyhow::bail!(
            "identity changes require the canonical identity owner; generic reconciliation is unsupported"
        )
    }

    async fn verify_state(&self, _desired: &Value) -> Result<bool> {
        anyhow::bail!("identity verification requires the canonical private credential reader")
    }

    async fn create_checkpoint(&self) -> Result<Checkpoint> {
        anyhow::bail!("identity credentials do not support generic checkpoints")
    }

    async fn rollback(&self, _checkpoint: &Checkpoint) -> Result<()> {
        anyhow::bail!(
            "identity recovery requires the canonical durable owner; generic rollback is unsupported"
        )
    }

    fn capabilities(&self) -> PluginCapabilities {
        PluginCapabilities {
            supports_rollback: false,
            supports_checkpoints: false,
            supports_verification: false,
            atomic_operations: false,
        }
    }
}

