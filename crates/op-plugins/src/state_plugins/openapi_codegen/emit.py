#!/usr/bin/env python3
"""Assemble the committed `<plugin>/api_types.rs` from typify output plus the
generated operation table.
usage: emit.py <state_plugins/<plugin>> <work-dir> <typify-version>"""
import hashlib, json, os, sys

plugin_dir, work, typify = sys.argv[1:4]
api = os.path.basename(os.path.abspath(plugin_dir))
base = os.path.join(plugin_dir, "openapi")
sel = json.load(open(os.path.join(base, "select.json")))
src = json.load(open(os.path.join(base, "source.json")))
spec = os.path.join(base, sel["spec"])
digest = hashlib.sha256(open(spec, "rb").read()).hexdigest()
if digest != src["sha256"] or sel["spec"] != src["file"]:
    sys.exit(f"{spec}: sha256 {digest} does not match {api}/openapi/source.json")
methods = json.load(open(os.path.join(work, f"{api}.methods.json")))
body = open(os.path.join(work, f"{api}.rs")).read()

out = []
out.append(f"// @generated by state_plugins/openapi_codegen/regenerate.sh -- DO NOT EDIT.")
out.append(f"//")
out.append(f"// Source: {src['url']}")
out.append(f"// Upstream: {src['project']} tag {src['tag']} (commit {src['commit']})")
out.append(f"// Spec sha256: {digest}" + (f" (upstream {src['upstream_sha256']}, redacted: see source.json)" if src.get("upstream_sha256") else ""))
out.append(f"// Spec: {api}/openapi/{sel['spec']}   Errata: {api}/openapi/errata.json   Selection: {api}/openapi/select.json")
out.append(f"// Generator: openapi_codegen/prepare.py + cargo-typify {typify} (--no-builder -d schemars::JsonSchema)")
out.append("#![allow(dead_code, missing_docs, unused_imports, clippy::all)]")
out.append(body.rstrip())
out.append("")
out.append("/// One selected upstream operation: the plugin method that exposes it, the")
out.append("/// HTTP method and path template (relative to the API base), the upstream")
out.append("/// operationId and the generated input/output type names.")
out.append("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
out.append("pub struct Operation {")
out.append("    pub method: &'static str,")
out.append("    pub http_method: &'static str,")
out.append("    pub path: &'static str,")
out.append("    pub operation_id: &'static str,")
out.append("    pub input: &'static str,")
out.append("    pub output: &'static str,")
out.append("}")
out.append("")
out.append(f"pub const SPEC_SHA256: &str = \"{digest}\";")
out.append(f"pub const UPSTREAM_TAG: &str = \"{src['tag']}\";")
out.append("")
out.append("pub const OPERATIONS: &[Operation] = &[")
for name in sorted(methods):
    m = methods[name]
    out.append(f"    Operation {{ method: {json.dumps(name)}, http_method: {json.dumps(m['http_method'])}, "
               f"path: {json.dumps(m['path'])}, operation_id: {json.dumps(m['operation_id'])}, "
               f"input: {json.dumps(m['input'])}, output: {json.dumps(m['output'])} }},")
out.append("];")
print("\n".join(out))
