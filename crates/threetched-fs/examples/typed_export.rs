//! Derive review artifacts from the plugin-owned contract; JSON is never an input.
#[path = "../../op-plugins/src/state_plugins/tched_fs_contract.rs"]
mod tched_fs_contract;

use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail, ensure};
use serde_json::json;

fn exports() -> Result<Vec<(&'static str, Vec<u8>)>> {
    let contract = tched_fs_contract::document();
    ensure!(
        contract["versioning"]["schema_version"] == tched_fs_contract::schema_version()
            && contract["versioning"]["source_commit"] == tched_fs_contract::source_commit(),
        "contract accessors and embedded versioning disagree"
    );
    jsonschema::draft202012::meta::validate(&contract)
        .map_err(|error| anyhow::anyhow!("invalid embedded JSON Schema: {error}"))?;
    let schema = tched_fs_contract::schema_document();
    jsonschema::Validator::new(&schema)?
        .validate(&contract)
        .map_err(|error| anyhow::anyhow!("embedded contract fails its own schema: {error}"))?;
    let binding = json!({
        "authority": {
            "authoring_source": contract["authority"]["authoring_source"],
            "derivation": "Generated by typed_export from the plugin-owned document; do not edit this file."
        },
        "types": contract["types"],
        "methods": contract["methods"],
        "bindings": contract["bindings"]
    });
    let nodes = json!({
        "authority": contract["authority"],
        "versioning": contract["versioning"],
        "nodes": contract["nodes"],
        "enumeration": contract["enumeration"],
        "fuse_operations": contract["fuse_operations"],
        "class_fuse_operations": contract["class_fuse_operations"],
        "invariants": contract["invariants"],
        "absent_surfaces": contract["absent_surfaces"],
        "source_payload_types": contract["source_payload_types"],
        "source_error_shapes": contract["source_error_shapes"],
        "protocol_extras": contract["protocol_extras"],
        "verification": contract["verification"]
    });
    [
        ("typed-filesystem.schema.json", contract.clone()),
        ("typed-filesystem-binding-input.json", binding),
        (
            "typed-filesystem-provenance.json",
            contract["versioning"].clone(),
        ),
        ("typed-filesystem-nodes.evidence.json", nodes),
        (
            "typed-filesystem-backing.evidence.json",
            contract["backing_evidence"].clone(),
        ),
        ("typed-filesystem-gaps.json", contract["gaps"].clone()),
        (
            "typed-filesystem-policy.json",
            contract["proposed_rw_policy_and_memory_strategy"].clone(),
        ),
        (
            "typed-filesystem-verification.json",
            contract["verification"].clone(),
        ),
    ]
    .into_iter()
    .map(|(name, value)| {
        let mut bytes = serde_json::to_vec_pretty(&value)?;
        bytes.push(b'\n');
        Ok((name, bytes))
    })
    .collect()
}

fn export(directory: &Path, check: bool) -> Result<()> {
    let documents = exports()?;
    if !check {
        std::fs::create_dir_all(directory)?;
    }
    for (name, bytes) in documents {
        let path = directory.join(name);
        if check {
            let current = std::fs::read(&path)
                .with_context(|| format!("missing export {}; run typed_export", path.display()))?;
            ensure!(
                current == bytes,
                "stale export {}; run typed_export",
                path.display()
            );
        } else {
            std::fs::write(&path, bytes).with_context(|| format!("writing {}", path.display()))?;
        }
    }
    Ok(())
}

fn main() -> Result<()> {
    let mut check = false;
    let mut directory = PathBuf::from("crates/threetched-fs/docs");
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--check" => check = true,
            "--out-dir" => directory = args.next().context("--out-dir requires a path")?.into(),
            _ => bail!("unknown argument {arg}; expected --check or --out-dir PATH"),
        }
    }
    export(&directory, check)?;
    println!(
        "{} plugin-owned 3tchedFS contract exports in {}",
        if check { "Verified" } else { "Wrote" },
        directory.display()
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::Value;

    #[test]
    fn owned_document_has_no_reused_mutable_decode() {
        let mut first = tched_fs_contract::document();
        first["types"] = json!({});
        let second = tched_fs_contract::document();
        assert!(!second["types"].as_object().unwrap().is_empty());
        assert_eq!(second["authority"]["owner_plugin"], "tched_fs");
        assert_eq!(second["authority"]["deployment"]["status"], "source-only");
    }

    #[test]
    fn flattened_schema_and_exact_sealed_constant_validate() {
        let contract = tched_fs_contract::document();
        let mut schema = tched_fs_contract::schema_document();
        assert_eq!(schema["type"], "object");
        assert!(schema.get("$ref").is_none());
        assert_eq!(schema["$defs"], contract["$defs"]);
        schema["const"] = contract.clone();
        let validator = jsonschema::Validator::new(&schema).unwrap();
        assert!(validator.is_valid(&contract));
        let mut tampered = contract;
        tampered["authority"]["owner_plugin"] = json!("alternate_authority");
        assert!(!validator.is_valid(&tampered));
    }

    #[test]
    fn exports_are_deterministic_and_check_rejects_drift() {
        assert_eq!(exports().unwrap(), exports().unwrap());
        let directory = tempfile::tempdir().unwrap();
        export(directory.path(), false).unwrap();
        export(directory.path(), true).unwrap();
        let path = directory.path().join("typed-filesystem.schema.json");
        std::fs::write(&path, b"{}\n").unwrap();
        assert!(export(directory.path(), true).is_err());
    }

    #[test]
    fn all_review_artifacts_derive_current_authority_and_preserve_history() {
        let source = tched_fs_contract::document();
        let output = exports().unwrap();
        assert_eq!(output.len(), 8);
        let document = |name: &str| -> Value {
            serde_json::from_slice(
                &output
                    .iter()
                    .find(|(filename, _)| *filename == name)
                    .unwrap()
                    .1,
            )
            .unwrap()
        };
        let binding = document("typed-filesystem-binding-input.json");
        for key in ["types", "bindings", "methods"] {
            assert_eq!(binding[key], source[key]);
        }
        let exported = document("typed-filesystem.schema.json");
        for key in [
            "verification",
            "gaps",
            "proposed_rw_policy_and_memory_strategy",
        ] {
            assert_eq!(exported[key], source[key]);
        }
        assert_eq!(exported["verification"]["task_id"], "fs-core-20261005");
        assert_eq!(
            exported["verification"]["historical"]["fs_schema_20261005"]["task_id"],
            "fs-schema-20261005"
        );
        for (filename, section) in [
            ("typed-filesystem-backing.evidence.json", "backing_evidence"),
            ("typed-filesystem-gaps.json", "gaps"),
            (
                "typed-filesystem-policy.json",
                "proposed_rw_policy_and_memory_strategy",
            ),
            ("typed-filesystem-verification.json", "verification"),
            ("typed-filesystem-provenance.json", "versioning"),
        ] {
            assert_eq!(document(filename), source[section]);
        }
        let nodes = document("typed-filesystem-nodes.evidence.json");
        for section in [
            "nodes",
            "enumeration",
            "fuse_operations",
            "class_fuse_operations",
            "invariants",
            "verification",
        ] {
            assert_eq!(nodes[section], source[section]);
        }
        assert!(
            source["nodes"]
                .as_array()
                .unwrap()
                .iter()
                .all(|node| node["class"] != "Outcome")
        );
    }

    fn protobuf_numbers(value: &Value) -> Value {
        match value {
            Value::Number(number) => json!(number.as_f64().unwrap()),
            Value::Array(values) => Value::Array(values.iter().map(protobuf_numbers).collect()),
            Value::Object(values) => Value::Object(
                values
                    .iter()
                    .map(|(key, value)| (key.clone(), protobuf_numbers(value)))
                    .collect(),
            ),
            other => other.clone(),
        }
    }

    #[test]
    fn u64_bound_is_exact_through_protobuf_schema_numbers() {
        let contract = tched_fs_contract::document();
        let too_large: Value = serde_json::from_str("18446744073709551616").unwrap();
        for schema in [
            contract["$defs"]["U64"].clone(),
            protobuf_numbers(&contract["$defs"]["U64"]),
        ] {
            let validator = jsonschema::Validator::new(&schema).unwrap();
            assert!(validator.is_valid(&json!(u64::MAX)));
            assert!(!validator.is_valid(&too_large));
            assert!(!validator.is_valid(&json!(-1)));
        }
    }

    #[test]
    fn protobuf_value_roundtrip_preserves_exact_contract_semantics() {
        let source = tched_fs_contract::document();
        let transported = protobuf_numbers(&source);
        let exact_schema = json!({"const": source});
        let validator = jsonschema::Validator::new(&exact_schema).unwrap();
        assert!(validator.is_valid(&transported));
        let transported_exact_schema = protobuf_numbers(&exact_schema);
        let transported_validator = jsonschema::Validator::new(&transported_exact_schema).unwrap();
        assert!(transported_validator.is_valid(&tched_fs_contract::document()));
    }
}
