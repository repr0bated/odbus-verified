//! Generate Rust bindings from the filesystem inventory, not from a second plugin schema.
use std::fmt::Write as _;
use std::io::Write as _;
use std::path::PathBuf;
use std::process::{Command, Stdio};

use anyhow::{Context, Result, bail, ensure};
use serde_json::Value;

fn identifier(value: &str) -> Result<&str> {
    ensure!(
        !value.is_empty()
            && value.bytes().enumerate().all(|(i, c)| c == b'_'
                || c.is_ascii_alphabetic()
                || (i > 0 && c.is_ascii_digit())),
        "invalid Rust identifier {value:?}"
    );
    Ok(value)
}
fn string<'a>(value: &'a Value, key: &str) -> Result<&'a str> {
    value[key]
        .as_str()
        .with_context(|| format!("missing string {key}"))
}
fn generate(schema: &Value) -> Result<String> {
    let types = schema["types"]
        .as_object()
        .context("missing types object")?;
    let classes = schema["bindings"]["classes"]
        .as_object()
        .context("missing bindings.classes")?;
    // Final inventory methods are reviewed independently of code-generation handler choices.
    if let Some(methods) = schema.get("methods") {
        let methods = methods.as_array().context("methods must be a flat array")?;
        for method in methods {
            for key in ["name", "receiver", "route"] {
                ensure!(method.get(key).is_some(), "method is missing {key}");
            }
        }
        let mut expected_count = 0;
        for (class, spec) in classes {
            for route in spec["routes"].as_array().context("class routes")? {
                for operation in spec["operations"].as_array().context("class operations")? {
                    expected_count += 1;
                    let matching: Vec<_> = methods
                        .iter()
                        .filter(|method| {
                            method["receiver"] == *class
                                && method["name"] == operation["name"]
                                && method["route"] == *route
                        })
                        .collect();
                    ensure!(
                        matching.len() == 1,
                        "flat method {class}.{} route {route} missing or duplicated",
                        operation["name"]
                    );
                    let method = matching[0];
                    ensure!(
                        method["borrow"] == operation["receiver"]
                            && method["returns"] == operation["return"]
                            && method["errors"] == format!("{class}Error"),
                        "flat method signature conflicts with generated class"
                    );
                    let params = method["params"].as_array().context("flat method params")?;
                    let args = operation["args"].as_array().context("class args")?;
                    ensure!(
                        params.len() == args.len()
                            && params
                                .iter()
                                .zip(args)
                                .all(|(param, arg)| param["name"] == arg["name"]
                                    && param["type"] == arg["type"]),
                        "flat method params conflict with generated class"
                    );
                }
            }
        }
        ensure!(
            methods.len() == expected_count,
            "flat method inventory contains extra methods without class implementations"
        );
    }
    let mut out = String::from(
        "// @generated by examples/typed_generate.rs from docs/typed-filesystem.schema.json.\n// Do not edit; this is a derived filesystem binding, never a plugin schema authority.\n#![allow(dead_code)]\nuse crate::typed_runtime::NodeHandle;\n",
    );
    for (name, spec) in types {
        ensure!(
            spec["source_refs"]
                .as_array()
                .is_some_and(|v| !v.is_empty()),
            "{name} has no source evidence"
        );
        if name.contains('<') {
            ensure!(
                name == "BlobRef<T>" || name == "ShmHandle<T>",
                "unsupported generic type {name}"
            );
        } else {
            identifier(name)?;
        }
        if matches!(
            spec["kind"].as_str(),
            Some("binding_node" | "binding_error" | "evidence_only")
        ) {
            continue;
        }
        writeln!(out, "/// Source: {}", spec["source_refs"])?;
        match string(spec, "kind")? {
            "alias" => {
                writeln!(out, "pub type {name} = {};", string(spec, "rust")?)?;
            }
            "struct" => {
                writeln!(
                    out,
                    "#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]\npub struct {name} {{"
                )?;
                for (field, ty) in spec["fields"].as_object().context("missing fields")? {
                    if ty.as_str().is_some_and(|ty| ty.starts_with("Option<")) {
                        writeln!(out, "#[serde(default)]")?;
                    }
                    writeln!(
                        out,
                        "pub {}: {},",
                        identifier(field)?,
                        ty.as_str().context("field type must be string")?
                    )?;
                }
                writeln!(out, "}}")?;
            }
            "enum" => {
                writeln!(
                    out,
                    "#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]"
                )?;
                if let Some(rename) = spec["serde_rename_all"].as_str() {
                    writeln!(out, "#[serde(rename_all={rename:?})]")?;
                }
                writeln!(out, "pub enum {name} {{")?;
                for (variant, ty) in spec["variants"].as_object().context("missing variants")? {
                    if ty.is_null() {
                        writeln!(out, "{},", identifier(variant)?)?;
                    } else {
                        writeln!(
                            out,
                            "{}({}),",
                            identifier(variant)?,
                            ty.as_str().context("variant type must be string")?
                        )?;
                    }
                }
                writeln!(out, "}}")?;
            }
            "validated_string" => {
                let validator = identifier(string(spec, "validator")?)?;
                writeln!(
                    out,
                    "#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, serde::Serialize)]\n#[serde(transparent)]\npub struct {name}(String);\nimpl {name} {{ pub fn new(value: impl Into<String>) -> Result<Self, NodeError> {{ let value=value.into(); crate::typed_runtime::validate_{validator}(&value)?; Ok(Self(value)) }} pub fn as_str(&self)->&str {{ &self.0 }} }}\nimpl<'de> serde::Deserialize<'de> for {name} {{fn deserialize<D:serde::Deserializer<'de>>(deserializer:D)->Result<Self,D::Error>{{let value=<String as serde::Deserialize>::deserialize(deserializer)?;Self::new(value).map_err(serde::de::Error::custom)}}}}"
                )?;
            }
            "validated_index" => {
                writeln!(
                    out,
                    "#[derive(Debug,Clone,Copy,PartialEq,Eq,serde::Serialize,serde::Deserialize)]\n#[serde(transparent)]\npub struct {name}(usize);\nimpl {name} {{ pub fn new(value:usize)->Self {{Self(value)}} pub fn get(self)->usize {{self.0}} }}"
                )?;
            }
            "recursive_json" => {
                writeln!(
                    out,
                    "#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]\n#[serde(untagged)]\npub enum {name} {{ Null, Bool(bool), Number(serde_json::Number), String(String), Array(Vec<{name}>), Object(std::collections::BTreeMap<String,{name}>) }}\nimpl {name} {{ pub fn into_json(self)->Result<serde_json::Value,NodeError>{{serde_json::to_value(self).map_err(NodeError::decode)}} pub fn from_json(value:serde_json::Value)->Result<Self,NodeError>{{serde_json::from_value(value).map_err(NodeError::decode)}} }}"
                )?;
            }
            "binding_node" | "binding_error" | "evidence_only" => {}
            kind => bail!("unsupported type kind {kind}"),
        }
    }
    for (name, spec) in classes {
        identifier(name)?;
        let error = format!("{name}Error");
        writeln!(
            out,
            "#[derive(Debug, thiserror::Error)]\npub enum {error} {{ #[error(\"binding contract: {{0}}\")] Contract(String), #[error(\"{{operation}}: {{message}} ({{kind:?}}, errno={{errno:?}})\")] Io {{operation:&'static str,condition:FsCondition,kind:std::io::ErrorKind,errno:Option<i32>,message:String}}, #[error(\"decode: {{0}}\")] Decode(String), #[error(\"schema: {{0}}\")] Schema(String), #[error(\"denied: {{0:?}}\")] Denied(JsonValue), #[error(\"terminal diagnostic ({{condition:?}}): {{diagnostic:?}}\")] Terminal {{condition:FsCondition,diagnostic:OperationDiagnostic,raw:JsonValue}}, #[error(\"completion uncertain; do not retry: {{0}}\")] Ambiguous(String), #[error(\"route unavailable: {{0}}\")] Unavailable(String) }}\nimpl From<NodeError> for {error} {{fn from(error:NodeError)->Self {{match error {{NodeError::Contract(v)=>Self::Contract(v),NodeError::Io{{operation,condition,kind,errno,message}}=>Self::Io{{operation,condition,kind,errno,message}},NodeError::Decode(v)=>Self::Decode(v),NodeError::Schema(v)=>Self::Schema(v),NodeError::Denied(v)=>Self::Denied(v),NodeError::Terminal{{condition,diagnostic,raw}}=>Self::Terminal{{condition,diagnostic,raw}},NodeError::Ambiguous(v)=>Self::Ambiguous(v),NodeError::Unavailable(v)=>Self::Unavailable(v)}}}}}}\npub struct {name}(pub(crate) NodeHandle);\npub trait {name}Methods {{"
        )?;
        let ops = spec["operations"]
            .as_array()
            .context("operations must be array")?;
        for op in ops {
            emit_method(&mut out, op, &error, false)?;
        }
        writeln!(out, "}}\nimpl {name}Methods for {name} {{")?;
        for op in ops {
            emit_method(&mut out, op, &error, true)?;
        }
        writeln!(out, "}}")?;
        for route in spec["routes"].as_array().context("missing class routes")? {
            let (prefix, route_key) = match route.as_str() {
                Some("direct-blob") => ("DirectBlob", "direct-blob"),
                Some("direct-shm") => ("DirectShm", "direct-shm"),
                Some("via-fuse") => ("ViaFuse", "via-fuse"),
                _ => bail!("unsupported route"),
            };
            writeln!(
                out,
                "pub struct {prefix}{name}(pub(crate) NodeHandle);\nimpl {name} {{pub fn into_{}(self)->Result<{prefix}{name},{error}> {{self.0.require_route({route_key:?}).map_err({error}::from)?;Ok({prefix}{name}(self.0))}}}}\nimpl {name}Methods for {prefix}{name} {{",
                if prefix == "DirectBlob" {
                    "direct_blob"
                } else if prefix == "DirectShm" {
                    "direct_shm"
                } else {
                    "via_fuse"
                }
            )?;
            for op in ops {
                emit_method(&mut out, op, &error, true)?;
            }
            writeln!(out, "}}")?;
        }
    }
    writeln!(out, "pub enum TypedNode {{")?;
    for name in classes.keys() {
        writeln!(out, "{name}({name}),")?;
    }
    writeln!(
        out,
        "}}\nimpl TypedNode {{ pub(crate) fn from_handle(handle:NodeHandle)->Self {{ match handle.kind() {{"
    )?;
    for name in classes.keys() {
        writeln!(
            out,
            "crate::typed_runtime::HandleKind::{name} => Self::{name}({name}(handle)),"
        )?;
    }
    writeln!(out, "}} }} }}")?;
    Ok(out)
}
fn emit_method(out: &mut String, op: &Value, error: &str, implementation: bool) -> Result<()> {
    let name = identifier(string(op, "name")?)?;
    let receiver = string(op, "receiver")?;
    ensure!(
        receiver == "&self" || receiver == "&mut self",
        "invalid receiver"
    );
    let handler = identifier(string(op, "handler")?)?;
    let args = op["args"].as_array().context("missing args")?;
    let mut declaration = receiver.to_string();
    let mut invocation = String::new();
    for arg in args {
        let arg_name = identifier(string(arg, "name")?)?;
        write!(declaration, ",{arg_name}:{}", string(arg, "type")?)?;
        if !invocation.is_empty() {
            invocation.push(',');
        }
        invocation.push_str(arg_name);
    }
    write!(
        out,
        "fn {name}({declaration}) -> Result<{}, {error}>",
        string(op, "return")?
    )?;
    if implementation {
        writeln!(
            out,
            " {{ self.0.{handler}({invocation}).map_err({error}::from) }}"
        )?;
    } else {
        writeln!(out, ";")?;
    }
    Ok(())
}
fn formatted(source: &str) -> Result<String> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .context("rustfmt is required for deterministic generated output")?;
    child
        .stdin
        .take()
        .context("rustfmt stdin")?
        .write_all(source.as_bytes())?;
    let result = child.wait_with_output()?;
    ensure!(
        result.status.success(),
        "rustfmt failed: {}",
        String::from_utf8_lossy(&result.stderr)
    );
    String::from_utf8(result.stdout).context("rustfmt output is not UTF-8")
}
fn main() -> Result<()> {
    let mut args = std::env::args().skip(1);
    let input = PathBuf::from(
        args.next()
            .unwrap_or_else(|| "crates/threetched-fs/docs/typed-filesystem.schema.json".into()),
    );
    let output = PathBuf::from(
        args.next()
            .unwrap_or_else(|| "crates/threetched-fs/src/typed_bindings.rs".into()),
    );
    let check = args.next().as_deref() == Some("--check");
    ensure!(
        args.next().is_none(),
        "usage: typed_generate [schema] [output] [--check]"
    );
    let schema: Value = serde_json::from_slice(&std::fs::read(&input)?)?;
    let source = formatted(&generate(&schema)?)?;
    if check {
        ensure!(
            std::fs::read_to_string(&output)? == source,
            "generated bindings differ; regenerate from {}",
            input.display()
        );
    } else {
        std::fs::write(&output, source)?;
    }
    println!(
        "{} {}",
        if check { "verified" } else { "generated" },
        output.display()
    );
    Ok(())
}
