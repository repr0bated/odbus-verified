#!/bin/sh
# Import the 3tched.com chat Canvas contract into the json_render plugin.
#
# The UI owns its Canvas catalog; `npm run references:export` in the UI
# checkout writes references/canvas-profile.json from it. This embeds that
# exact document, with its source commit and digest, as the plugin-owned
# constant the backend validates saved and promoted canvases against.
#
# Usage: scripts/import-chat-canvas-profile.sh [ui-checkout]   (default /srv/git/3tched.com)
set -eu
ui="${1:-/srv/git/3tched.com}"
src="$ui/references/canvas-profile.json"
out="$(git rev-parse --show-toplevel)/crates/op-plugins/src/state_plugins/json_render_chat_canvas_contract.rs"
[ -f "$src" ] || { echo "missing $src: run 'npm run references:export' in $ui first" >&2; exit 1; }
jq -e '.format == "3tched.canvas-profile.v1" and (.components | length > 0)' "$src" >/dev/null \
  || { echo "$src is not a 3tched.canvas-profile.v1 document" >&2; exit 1; }
revision="$(git -C "$ui" rev-parse HEAD)"
if [ -n "$(git -C "$ui" status --porcelain -- references/canvas-profile.json src/json-render)" ]; then
  revision="$revision+modified"
fi
compact="$(jq -cS . "$src")"
digest="$(printf '%s' "$compact" | sha256sum | cut -d' ' -f1)"
case "$compact" in *'"####'*) echo "profile contains the raw-string delimiter" >&2; exit 1 ;; esac
{
  echo '//! Generated by scripts/import-chat-canvas-profile.sh from the 3tched.com'
  echo '//! Canvas catalog export. Do not edit; re-run the importer instead.'
  echo ''
  echo 'pub(crate) const SOURCE_REPOSITORY: &str = "github.com/repr0bated/3tched.com";'
  echo "pub(crate) const SOURCE_REVISION: &str = \"$revision\";"
  echo "/// sha256 of PROFILE_JSON."
  echo "pub(crate) const PROFILE_SHA256: &str = \"$digest\";"
  printf 'pub(crate) const PROFILE_JSON: &str = r####"%s"####;\n' "$compact"
} > "$out"
echo "wrote $out ($revision, $digest)"
